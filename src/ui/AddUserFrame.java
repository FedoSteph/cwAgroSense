    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        // 🔒 VALIDATE UID FIRST
if (jTextField6.getText().trim().isEmpty()) {
JOptionPane.showMessageDialog(this, "UID is required!");
return;
}


int uid = Integer.parseInt(jTextField6.getText());


// ❌ UID 0 IS NOT ALLOWED
if (uid == 0) {
JOptionPane.showMessageDialog(this, "UID cannot be 0");
return;
}
        try {
    // 1️⃣ Insert USER
    User user = new User();
user.setuid(uid); // 🔑 THIS LINE MUST EXIST
user.setUsername(jTextField1.getText());
user.setEmail(jTextField2.getText());
user.setPassword(new String(jPasswordField1.getPassword()));
user.setRole(jComboBox1.getSelectedItem().toString());

    UserDAO userDAO = new UserDAO();


boolean ok = userDAO.insertUser(user);


if (!ok) {
JOptionPane.showMessageDialog(this, "User save failed");
return;
}




    // 2️⃣ Insert FARMER
    if (user.getRole().equals("FARMER")) {
        Farmer f = new Farmer();
        f.setuid(uid);
        f.setContactNo(jTextField3.getText());
        f.setLocation(jTextField4.getText());

        new FarmerDAO().insertFarmer(f);
    }

    // 3️⃣ Insert BUYER
    if (user.getRole().equals("BUYER")) {
        Buyer b = new Buyer();
        b.setUid(uid);
        b.setCompanyName(jTextField5.getText());

        new BuyerDAO().insertBuyer(b);
    }

    JOptionPane.showMessageDialog(this, "User added successfully");

} catch (Exception e) {
    e.printStackTrace();
    JOptionPane.showMessageDialog(this, "Error occurred");
}

    }//GEN-LAST:event_jButton1ActionPerformed

