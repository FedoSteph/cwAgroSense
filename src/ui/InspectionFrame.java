    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
         try {
        
        String scidText = jComboBox1.getSelectedItem().toString();
        int scid = Integer.parseInt(scidText);

        
        String dateText = jTextField1.getText();
        String result = jComboBox2.getSelectedItem().toString();
        String remarks = jTextArea1.getText();

        java.util.Date date =
            new java.text.SimpleDateFormat("yyyy-MM-dd").parse(dateText);

        
        Inspection ins = new Inspection();
        ins.setScid(scid);
        ins.setInspectionDate(date);
        ins.setResult(result);
        ins.setRemarks(remarks);

        
        InspectionDAO dao = new InspectionDAO();

        if (dao.insertInspection(ins)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Inspection Saved");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Save Failed");
        }

    } catch (Exception e) {
        e.printStackTrace();
        javax.swing.JOptionPane.showMessageDialog(this, "Invalid Data");
    }
    }//GEN-LAST:event_jButton1ActionPerformed

