    private void jComboBox1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBox1ActionPerformed
        
        
if (jComboBox1.getSelectedItem() == null) {
return;
}
        
        try {
    String type = jComboBox1.getSelectedItem().toString();

    if (type.equals("USERS")) {
        loadTable(new UserDAO().getAllUsers());
    }

    if (type.equals("FARMERS")) {
        loadTable(new FarmerDAO().getFarmersWithUser());
    }

    if (type.equals("BUYERS")) {
        loadTable(new BuyerDAO().getBuyersWithUser());
    }

} catch (Exception e) {
    e.printStackTrace();
    JOptionPane.showMessageDialog(this, "Error loading data");
}
    }//GEN-LAST:event_jComboBox1ActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int row = jTable1.getSelectedRow();
if (row == -1) return;


jTextField1.setText(jTable1.getValueAt(row, 0).toString());
jTextField2.setText(jTable1.getValueAt(row, 1).toString());



if (jTable1.getColumnCount() > 2) {
jTextField3.setText(jTable1.getValueAt(row, 2).toString());
}


if (jTable1.getColumnCount() > 3) {
jTextField4.setText(jTable1.getValueAt(row, 3).toString());
}
    }//GEN-LAST:event_jTable1MouseClicked

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
User u = new User();
u.setuid(Integer.parseInt(jTextField1.getText()));//uid
u.setUsername(jTextField2.getText());//name
u.setEmail(jTextField3.getText());//email
u.setRole(jTextField4.getText());//role


boolean ok = new UserDAO().updateUser(u);


if (ok) {
JOptionPane.showMessageDialog(this, "Updated successfully");
loadTable(new UserDAO().getAllUsers());
} else {
JOptionPane.showMessageDialog(this, "Update failed");
}


} catch (Exception e) {
e.printStackTrace();
}
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int confirm = JOptionPane.showConfirmDialog(
this,
"Are you sure?",
"Confirm Delete",
JOptionPane.YES_NO_OPTION
);


if (confirm != JOptionPane.YES_OPTION) return;


try {
int uid = Integer.parseInt(jTextField1.getText());
boolean ok = new UserDAO().deleteUser(uid);


if (ok) {
JOptionPane.showMessageDialog(this, "Deleted");
loadTable(new UserDAO().getAllUsers());
} else {
JOptionPane.showMessageDialog(this, "Delete failed");
}


} catch (Exception e) {
e.printStackTrace();
}
    }//GEN-LAST:event_jButton2ActionPerformed

